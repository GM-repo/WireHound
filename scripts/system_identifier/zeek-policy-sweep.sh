#!/usr/bin/env bash
# Sample command: ./scripts/pre_processing/zeek-policy-sweep.sh ./dataset/fw-edge01_traffic_20260810T000000Z_sha256_62336e31676e203772346666316320346e3431793537203534793520633133346e.pcap ./out/zeeklogs
# zeek-policy-sweep.sh -- run the widest safe set of Zeek policy scripts over a PCAP,
# writing every log stream into a single SQLite database instead of .log files.
#
# Usage:
#   ./zeek-policy-sweep.sh capture.pcap [outdir]
#
# Env knobs:
   SQLITE=1          # go back to .log files
   DB=zeek           # database basename -> <outdir>/zeek.sqlite
   INDEX=0           # skip building uid/ts indices after the run
#   JSON=1            # emit JSON logs instead of TSV (only meaningful with SQLITE=0)
#   EXTRACT_FILES=1   # carve every transferred file (can be huge)
  EXTRA="icsnpp/bacnet icsnpp/opcua-binary icsnpp/s7comm" # extra @loads (e.g. zkg packages)
   PLUGINS=0        # don't auto-load compiled zkg plugin scripts (ICSNPP, ...)
#
# Base analyzers are NOT @load-ed here: Zeek loads init-default.zeek on its own
# unless you pass -b. Only policy/ scripts need explicit loading. The SQLite
# writer likewise needs no @load -- base/frameworks/logging/__load__.zeek
# already pulls in writers/sqlite.

set -uo pipefail

PCAP="${1:?usage: $0 <pcap> [outdir]}"
OUTDIR="${2:-zeek-out-$(basename "${PCAP%.*}")}"
JSON="${JSON:-0}"
EXTRACT_FILES="${EXTRACT_FILES:-0}"
EXTRA="${EXTRA:-}"
SQLITE="${SQLITE:-1}"
DB="${DB:-zeek}"
INDEX="${INDEX:-1}"
PLUGINS="${PLUGINS:-1}"

command -v zeek >/dev/null || { echo "zeek not on PATH"; exit 1; }
[[ -r "$PCAP" ]] || { echo "cannot read $PCAP"; exit 1; }

if [[ "$SQLITE" == "1" && "$JSON" == "1" ]]; then
  echo "== JSON=1 is meaningless with SQLITE=1 (the ASCII writer is never used); ignoring"
  JSON=0
fi

echo "== $(zeek --version 2>&1 | head -1)"
SCRIPTDIR="$(zeek-config --script_dir 2>/dev/null || echo /opt/zeek/share/zeek)"
echo "== script dir: $SCRIPTDIR"

DENY='^(misc/(dump-events|profiling|trim-trace-file)|frameworks/(control|cluster|netcontrol)/|frameworks/analyzer/debug-logging|frameworks/files/(detect-MHR|extract-all-files)|frameworks/notice/actions/(drop|page|email_admin)|integration/barnyard2/|protocols/ssl/(log-hostcerts-only|decryption)|tuning/json-logs)'

mapfile -t CANDIDATES < <(
  { find "$SCRIPTDIR/policy" -name __load__.zeek -printf '%h\n'
    find "$SCRIPTDIR/policy" -name '*.zeek' ! -name '__load__.zeek' -printf '%p\n' | sed 's/\.zeek$//'
  } | sed "s|^$SCRIPTDIR/policy/||" | sort -u | awk '
    { all[NR]=$0; seen[$0]=1 }
    END { for (i=1;i<=NR;i++) { p=all[i]; drop=0
            while (sub(/\/[^\/]*$/,"",p)) if (p in seen) { drop=1; break }
            if (!drop) print all[i] } }' | grep -Ev "$DENY"
)

mkdir -p "$OUTDIR"
OUTABS="$(cd "$OUTDIR" && pwd)"
CFG="$OUTDIR/policy-sweep.zeek"
SQLCFG="$OUTDIR/sqlite-logs.zeek"
PROBE="$OUTDIR/_probe.zeek"
DBFILE="$OUTDIR/$DB.sqlite"
CFG_LINES=()

# Stage 1: keep only paths that exist in THIS Zeek version.
FOUND=0; MISSING=0
for s in "${CANDIDATES[@]}"; do
  if [[ -f "$SCRIPTDIR/policy/$s.zeek" || -d "$SCRIPTDIR/policy/$s" ]]; then
    CFG_LINES+=("@load policy/$s"); FOUND=$((FOUND+1))
  else
    MISSING=$((MISSING+1))
  fi
done
for e in $EXTRA; do CFG_LINES+=("@load $e"); done

# Stage 1b: compiled zkg plugins (e.g. ICSNPP). Zeek registers the C++ analyzers
# from the plugin path at startup, but each package's policy scripts -- log
# stream definitions, port/DPD registration, file extraction -- still need
# explicit @load. Their top-level scripts/__load__.zeek is an empty stub, so
# pick up every __load__.zeek below it. Stage 2 drops any that fail to parse.
if [[ "$PLUGINS" == "1" ]]; then
  PLUGINDIR="$(zeek-config --plugin_dir 2>/dev/null || echo /opt/zeek/lib/zeek/plugins)"
  NPLUGINS=0
  for d in "$PLUGINDIR"/packages/*/; do
    [[ -d "$d" ]] || continue
    while IFS= read -r l; do
      CFG_LINES+=("@load $l"); NPLUGINS=$((NPLUGINS+1))
    done < <(find "$d/scripts" -name __load__.zeek ! -path '*/scripts/__load__.zeek' 2>/dev/null)
  done
else
  NPLUGINS=0
fi
[[ "$EXTRACT_FILES" == "1" ]] && CFG_LINES+=("@load policy/frameworks/files/extract-all-files")

# Route every stream into one database, one table per stream. Written out as its
# own script so the generated config stays a flat list of one-line @load/redef
# statements that the stage-2 bisect can validate individually.
if [[ "$SQLITE" == "1" ]]; then
  cat > "$SQLCFG" <<'SQLITE_ZEEK'
##! Generated by zeek-policy-sweep.sh -- edits here are overwritten on the next run.
##!
##! Replaces each stream's default ASCII filter with a SQLite one pointed at a
##! single database file. Table names match what the .log files would have been.

module SQLiteLogs;

export {
	## Database basename. Zeek appends ".sqlite" and prefixes Log::default_logdir.
	const db = "zeek" &redef;
}

# Bulk offline ingest: skip fsync, use WAL so the per-stream writer threads
# aren't serialising on a rollback journal. Drop both for live capture.
redef LogSQLite::synchronous  = LogSQLite::SQLITE_SYNCHRONOUS_OFF;
redef LogSQLite::journal_mode = LogSQLite::SQLITE_JOURNAL_MODE_WAL;

# Base scripts create their streams at &priority=5, policy scripts usually at 0,
# so run below both and every stream will already exist.
event zeek_init() &priority=-10
	{
	for ( id, stream in Log::active_streams )
		{
		# The name the ASCII writer would have given the file.
		local tname = stream?$path ? stream$path
		                           : Log::default_path_func(id, "", "");

		Log::remove_default_filter(id);

		Log::add_filter(id, Log::Filter($name   = "sqlite",
		                                $writer = Log::WRITER_SQLITE,
		                                $path   = db,
		                                $config = table(["tablename"] = tname)));
		}
	}
SQLITE_ZEEK
  # The extension is mandatory here: Zeek only appends ".zeek" when resolving
  # a RELATIVE @load against ZEEKPATH. An absolute path is stat'ed verbatim.
  CFG_LINES+=("@load $OUTABS/sqlite-logs.zeek")
fi

# Tunables. Names drift between releases, so each is validated below and
# silently dropped if this Zeek doesn't know it.
CFG_LINES+=("redef Weird::sampling_threshold = 0;")            # log every weird, not a sample
CFG_LINES+=("redef Analyzer::disabled_analyzers = set();")     # turn on anything off by default
CFG_LINES+=("redef DPD::ignore_violations_after = 100000000;") # keep logging late violations

# Stage 2: validate. Try the whole set first; fall back to line-by-line bisect.
write_cfg() {
  local dest="$1"; shift            # <-- without the shift, $@ still holds dest
  printf '%s\n' "# generated $(date -u +%FT%TZ)" "$@" > "$dest"
}

write_cfg "$CFG" "${CFG_LINES[@]}"
if zeek -a "$CFG" >"$OUTDIR/parse.err" 2>&1; then
  echo "== policies: $FOUND found / $MISSING absent / $NPLUGINS plugin scripts; all lines parse clean"
else
  echo "== batch parse failed, validating line by line (~1 zeek call per line)..."
  KEPT=(); DROPPED=0
  : > "$OUTDIR/parse-errors.log"
  for l in "${CFG_LINES[@]}"; do
    write_cfg "$PROBE" "${KEPT[@]}" "$l"
    if zeek -a "$PROBE" >"$OUTDIR/parse.err" 2>&1; then
      KEPT+=("$l")
    else
      echo "   dropped: $l"
      sed -n '1,2p' "$OUTDIR/parse.err" | sed 's/^/       > /'
      # parse.err is clobbered every iteration; keep the full text of each
      # failure so a drop late in the list is still diagnosable.
      { echo "### $l"; cat "$OUTDIR/parse.err"; echo; } >> "$OUTDIR/parse-errors.log"
      DROPPED=$((DROPPED+1))
    fi
  done
  write_cfg "$CFG" "${KEPT[@]}"
  echo "== policies: $FOUND found / $MISSING absent / $NPLUGINS plugin scripts / $DROPPED rejected"
fi
rm -f "$PROBE"

# Did the SQLite loader survive validation? If not, say so loudly rather than
# quietly producing .log files.
SQLITE_ON=0
if [[ "$SQLITE" == "1" ]]; then
  if grep -qF "@load $OUTABS/sqlite-logs.zeek" "$CFG"; then
    SQLITE_ON=1
    echo "== SQLite: all streams -> $DBFILE (one table per stream)"
    # Tables are CREATE TABLE IF NOT EXISTS and rows only ever append, so a
    # re-run against a stale database silently doubles every count.
    rm -f "$DBFILE" "$DBFILE-wal" "$DBFILE-shm"
  else
    echo "== WARNING: SQLite loader rejected during validation; falling back to .log files"
  fi
fi

ARGS=(-C -r "$(readlink -f "$PCAP")" "$(basename "$CFG")")
[[ "$SQLITE_ON" == "1" ]] && ARGS+=("SQLiteLogs::db=$DB")
[[ "$JSON" == "1" ]] && ARGS+=(LogAscii::use_json=T)

echo "== running..."
( cd "$OUTDIR" && zeek "${ARGS[@]}" ) 2>&1 | tail -20

echo
if [[ "$SQLITE_ON" == "1" ]]; then
  if [[ ! -f "$DBFILE" ]]; then
    echo "== no database produced -- check the Zeek output above"
  elif ! command -v sqlite3 >/dev/null; then
    echo "== $DBFILE written ($(du -h "$DBFILE" | cut -f1)); sqlite3 not on PATH, skipping summary"
  else
    q()    { sqlite3 -noheader "$DBFILE" "$1"; }
    tbls() { q "SELECT name FROM sqlite_master WHERE type='table';"; }
    have() { [[ -n "$(q "SELECT 1 FROM sqlite_master WHERE type='table' AND name='$1';")" ]]; }

    echo "== tables in $DBFILE"
    for t in $(tbls); do
      printf '%12s %s\n' "$(q "SELECT count(*) FROM \"$t\";")" "$t"
    done | sort -rn | awk '{ printf "  %-24s %s rows\n", $2, $1 }'

    if [[ "$INDEX" == "1" ]]; then
      echo "== indexing uid / ts (the writer creates none)"
      for t in $(tbls); do
        for c in uid ts; do
          [[ -n "$(q "SELECT 1 FROM pragma_table_info('$t') WHERE name='$c';")" ]] &&
            q "CREATE INDEX IF NOT EXISTS \"${t}_${c}\" ON \"$t\"(\"$c\");"
        done
      done
    fi

    echo
    echo "== first stops for anomalies"
    have weird && { echo "-- weird"; sqlite3 -column "$DBFILE" \
      "SELECT name, count(*) AS n FROM weird GROUP BY name ORDER BY n DESC LIMIT 15;"; }
    have notice && { echo "-- notice"; sqlite3 -column "$DBFILE" \
      "SELECT note, count(*) AS n FROM notice GROUP BY note ORDER BY n DESC LIMIT 15;"; }
    have analyzer && { echo "-- analyzer"; sqlite3 -column "$DBFILE" \
      "SELECT analyzer_name, failure_reason, count(*) AS n FROM analyzer
         GROUP BY 1,2 ORDER BY n DESC LIMIT 10;"; }
    have capture_loss && { echo "-- capture_loss"; sqlite3 -column -header "$DBFILE" \
      "SELECT datetime(ts,'unixepoch') AS t, percent_lost FROM capture_loss
         ORDER BY ts DESC LIMIT 3;"; }
  fi

  # Any stream whose default filter we missed (created after zeek_init, or a
  # policy script that added its own named ASCII filter) still writes a file.
  if compgen -G "$OUTDIR/*.log" >/dev/null; then
    echo
    echo "== NOTE: these streams still wrote ASCII and are NOT in the database"
    ls -1 "$OUTDIR"/*.log | sed 's|^|  |'
  fi
else
  echo "== logs produced"
  ls -S "$OUTDIR"/*.log 2>/dev/null | while read -r f; do
    printf '  %-22s %s lines\n' "$(basename "$f")" "$(($(wc -l < "$f") - 8))"
  done

  echo
  echo "== first stops for anomalies"
  for f in weird.log notice.log analyzer.log dpd.log capture_loss.log; do
    [[ -f "$OUTDIR/$f" ]] || continue
    echo "-- $f"
    if command -v zeek-cut >/dev/null; then
      case "$f" in
        weird.log)    zeek-cut name < "$OUTDIR/$f" | sort | uniq -c | sort -rn | head -15 ;;
        notice.log)   zeek-cut note < "$OUTDIR/$f" | sort | uniq -c | sort -rn | head -15 ;;
        analyzer.log) zeek-cut analyzer_name failure_reason < "$OUTDIR/$f" | sort | uniq -c | sort -rn | head -10 ;;
        *)            tail -3 "$OUTDIR/$f" ;;
      esac
    else
      tail -5 "$OUTDIR/$f"
    fi
  done
fi

sqlite3 $DBFILE ".schema" >> $OUTDIR/schema

